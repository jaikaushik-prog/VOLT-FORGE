"""Write the recommendation from the study summary, so every figure traces to a result."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT/'reports/design_study_v2/run1'
s = json.loads((RUN/'summary.json').read_text()); manifest = json.loads((RUN/'manifest.json').read_text())
designs = {(d['count'], d['option']): d for d in s['designs']}
rec = s['recommended']; best = designs[(rec['count'], rec['option'])]; base = designs[(rec['count'], 'baseline')]; four = designs[(4, 'baseline')]
effect = s['option_effects'][f"{rec['count']}_{rec['option']}_pi"]
stress, pi = best['samples']['stress'], best['samples']['pi']
rows = '\n'.join(f"| {d['count']} | {'Qualifies' if d['qualifies'] else 'Refused'} | {d['required_passed']} of {d['required_cases']} | "
                 + (f"{d['nominal']['min_voltage_V']:.2f} V | {d['nominal']['peak_cell_current_A']:.2f} A | {d['worst_required']['highest_cell_current_A']:.2f} A | {d['worst_required']['highest_temperature_C']:.1f} °C" if d['qualifies'] else '— | — | — | —')
                 + f" | ₹{d['cell_cost_inr']:,.0f} | {d['cell_mass_g']:.0f} g |" for d in s['designs'] if d['option'] == 'baseline')
text = f"""# Recommendation

**Use {rec['count']} LG M50T cells in parallel, with the negative output at the far cell, for the Raspberry Pi 5 gateway backup.** It is the {s['claim'].lower()}.

This is a simulation result. Nothing here has been built or measured. Generated by `scripts/write_recommendation.py` from `reports/design_study_v2/run1/summary.json`, software `{manifest['software_hash'][:16]}`.

## The result

The mission is 25 W for 10 minutes through an assumed 90% converter, held at 8.42 A, with a 3.3 V floor at 23 °C. A design qualifies only if every required Pi case passes: nominal, mismatch at every cell position in both directions, thermal sensitivities and converter efficiency. That rule was committed before any case ran.

| Cells | Verdict | Required Pi cases | Lowest voltage | Peak cell current | Worst-case current | Worst-case temperature | Cell cost | Cell mass |
| ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
{rows}

Rows use same-end outputs. The cell limit is 7.275 A.

## Why {rec['count']} cells

- **One cell is refused.** At 8.42 A it exceeds the 7.275 A limit, in all {designs[(1, 'baseline')]['required_cases']} required cases.
- **{rec['count']} cells pass every required case.** Worst-case current is {best['worst_required']['highest_cell_current_A']:.2f} A, which leaves {best['current_margin_A']:.2f} A of margin, and the lowest voltage is {best['worst_required']['lowest_voltage_V']:.2f} V.
- **It halves the cell purchase.** ₹{four['cell_cost_inr']:,.0f} to ₹{best['cell_cost_inr']:,.0f}, and {four['cell_mass_g']:.0f} g to {best['cell_mass_g']:.0f} g. This is cells only, not a complete backup unit.
- **Temperature does not change the decision.** The worst {rec['count']}-cell case reaches {best['worst_required']['highest_temperature_C']:.1f} °C, including halved cooling and heat capacity.

## What argues against it

- **It has less margin.** Four cells stay at {four['worst_required']['highest_cell_current_A']:.2f} A in their worst required case, against {best['worst_required']['highest_cell_current_A']:.2f} A here.
- **The 12 A stress test can fail.** {stress['cases']-stress['passed']} of {stress['cases']} combined mismatch samples were refused for exceeding the cell limit. All {pi['cases']} samples passed at the Pi load. Samples show sensitivity, not a probability.
- **No link option wins everywhere.** The opposite-end output gave the best worst-case margin, {best['worst_required']['highest_cell_current_A']:.2f} A against {base['worst_required']['highest_cell_current_A']:.2f} A. It still raised peak current in {effect['raised_peak_current']} of {effect['pairs']} paired cases. The cell count is the real decision, and the output position is a small refinement.
- **Temperatures are not validated.** All 12 pre-declared measured comparison cases missed their bands. Treat temperatures as a range.
- **The board is unconfirmed.** The Geekworm X1206 V2.0 has four 21700 slots. Its listing does not confirm running with fewer than four cells fitted, and it publishes no battery cutoff or efficiency.

## Next step

Bench-test two cells on the board at a measured Pi draw, then run observed trials with students and engineers in Round 2.

## Numerical check

Halving the time step moved results by at most {s['half_step']['max_voltage_change_V']:.5f} V and {s['half_step']['max_temperature_change_K']:.4f} K across {s['half_step']['pairs']} pairs. {s['refused']} of {s['cases']:,} cases were refused by the product's limits. The first-law check closed in every calculated case.
"""
(ROOT/'reports/design_study_v2/RECOMMENDATION.md').write_text(text)
print(text[:1500])
