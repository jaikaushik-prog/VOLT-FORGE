"""Estimate the cost of building the full VOLT-FORGE vision, two independent ways."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
C = json.loads((ROOT/'configs/build_cost_v1.json').read_text())
RATES = {k: v['value'] for k, v in C['rates_lakh_per_year'].items()}
OVERHEAD = C['overhead_multiplier']['value']; YEARS = C['duration_years']; FX = C['usd_inr']['value']

rows = []
for item in C['work_breakdown_person_years']:
    staff = {k: v for k, v in item.items() if k in RATES}
    rows.append(dict(id=item['id'], name=item['name'], vision=item['vision'], person_years=sum(staff.values()), lakh=sum(RATES[k]*v for k, v in staff.items())*OVERHEAD))
people = sum(r['lakh'] for r in rows); person_years = sum(r['person_years'] for r in rows)
lab = sum(i['quantity']*(i.get('unit_inr') or i['unit_usd']*FX) for i in C['lab'])/1e5
recurring = sum(i['value'] for i in C['recurring_lakh_per_year'])*YEARS
one_off = sum(i['value'] for i in C['one_off_lakh'])
subtotal = people+lab+recurring+one_off; contingency = subtotal*C['contingency']['value']; total = subtotal+contingency

ksloc = sum(C['cross_check']['ksloc'].values()); months = 2.94*ksloc**1.0997
blended = people/person_years
cocomo = months/12*blended
aspen = C['benchmark']['usd_million']*FX*10  # Rs lakh per year: USD million x FX x 10.
result = dict(version='voltforge.build-cost-result/1', total_crore=total/100, total_usd_million=total*1e5/FX/1e6, person_years=person_years, average_team=person_years/YEARS,
              breakdown_crore=dict(people=people/100, lab=lab/100, recurring=recurring/100, one_off=one_off/100, contingency=contingency/100),
              work=[dict(r, crore=r['lakh']/100) for r in rows],
              cross_check=dict(ksloc=ksloc, person_months=months, person_years=months/12, software_people_crore=cocomo/100, bottom_up_people_crore=people/100, difference_pct=100*(cocomo/people-1)),
              benchmark=dict(aspentech_rd_crore_per_year=aspen/100, share_pct=100*total/aspen), scope=C['scope'])
out = ROOT/'reports/build_cost_v1'; out.mkdir(parents=True, exist_ok=True)
(out/'result.json').write_text(json.dumps(result, indent=2)+'\n')
table = '\n'.join(f"| {r['name']} | {r['vision']} | {r['person_years']:g} | ₹{r['lakh']/100:.1f} crore |" for r in rows)
(out/'BUILD_COST.md').write_text(f"""# What the full VOLT-FORGE would cost to build

**About ₹{total/100:.0f} crore over {YEARS} years, with {person_years:g} person-years of work.** This is an estimate, not a quote. Generated by `scripts/build_cost_model.py` from `configs/build_cost_v1.json`, where each input is marked sourced or assumed.

Scope: {C['scope']}

| Workstream | Vision | Person-years | Cost |
| --- | --- | ---: | ---: |
{table}

| Layer | Cost |
| --- | ---: |
| People, with {OVERHEAD}× overhead | ₹{people/100:.1f} crore |
| Lab equipment and cells | ₹{lab/100:.1f} crore |
| Lab running costs, cloud and tools | ₹{recurring/100:.1f} crore |
| Legal, IP and audits | ₹{one_off/100:.1f} crore |
| {100*C['contingency']['value']:.0f}% contingency | ₹{contingency/100:.1f} crore |
| **Total** | **₹{total/100:.1f} crore** |

## Cross-check

COCOMO II at {ksloc} thousand lines gives {months:,.0f} person-months, or {months/12:.0f} person-years. At the same blended rate that is ₹{cocomo/100:.1f} crore of people cost, {abs(100*(cocomo/people-1)):.0f}% {'below' if cocomo < people else 'above'} the bottom-up figure. COCOMO counts software only, so a lower figure is expected. The line count is an assumption.

## Benchmark

AspenTech spent US${C['benchmark']['usd_million']:.1f} million on R&D in fiscal 2024, about ₹{aspen/100:,.0f} crore at ₹{FX} a dollar. This build is {100*total/aspen:.1f}% of one such year. AspenTech covers far more domains, so this shows scale and is not a like-for-like price.

## Limits

Salary sources disagree widely, so the rates are stated role by role. Listings are not quotes. The person-years and line counts are engineering judgement, not measured data.
""")
print(json.dumps({k: result[k] for k in ('total_crore', 'total_usd_million', 'person_years', 'average_team', 'breakdown_crore', 'cross_check', 'benchmark')}, indent=1))
print(table)
