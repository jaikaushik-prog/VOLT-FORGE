from voltforge.models.identification import (unit_rc, fit_candidates, prepare,
    loaded_curve, bounded_two, verify_inputs, source_archive, read_cell)
from zipfile import ZipFile

ROOT=Path(__file__).resolve().parents[1]
PLAN=json.loads((ROOT/'configs/cell_identification_v1.json').read_text())


def test_rc_exact_step_and_relaxation_on_irregular_clock():
    # Synthetic constant 2 A pulse to t=3, then rest, then -1 A charge.
    t=np.array([0., .1, 1.7, 3., 4.2, 7., 9.])
    i=np.array([2.,2.,2.,0.,0.,-1.,-1.])
    x3=2*(1-np.exp(-3/5))
    expected=[0.,2*(1-np.exp(-.1/5)),2*(1-np.exp(-1.7/5)),x3,
              x3*np.exp(-1.2/5),x3*np.exp(-4/5),
              x3*np.exp(-6/5)-(1-np.exp(-2/5))]
    np.testing.assert_allclose(unit_rc(t,i,5),expected,atol=2e-15)
    with pytest.raises(ValueError): unit_rc([0,0],[1,1],5)


def test_parameter_recovery_uses_analytical_synthetic_pulses():
    # Closed-form response, not generated by the implementation under test.
    tau=float(np.geomspace(.2,300,121)[70]);r0=.023;r1=.014
    t=np.arange(0,100,.5);i=np.where(t<12,2.,np.where(t<50,0.,-1.))
    state=np.where(t<=12,2*(1-np.exp(-t/tau)),
                   2*(1-np.exp(-12/tau))*np.exp(-(t-12)/tau))
    state+=np.where(t>=50,-(1-np.exp(-(t-50)/tau)),0)
    f=pd.DataFrame({'time_s':t,'I_A':i,'reference_V':3.8,'V_V':3.8-r0*i-r1*state,'step':12})
    result=fit_candidates({c:f.copy() for c in PLAN['calibration_cycles']},PLAN['calibration_cycles'],PLAN)
    assert result['one_rc']['R0_ohm']==pytest.approx(r0,abs=1e-12)
    assert result['one_rc']['R1_ohm']==pytest.approx(r1,abs=1e-12)
    assert result['one_rc']['tau_s']==pytest.approx(tau,abs=1e-12)
    assert result['interior_identifiability_screen']


def test_loaded_curve_is_measured_loaded_voltage_and_charge_units():
    low=pd.DataFrame({'time_s':[0.,3600.,7200.],'I_A':[.5,.5,.5],'V_V':[4.1,3.7,3.]})
    capacity,soc,voltage=loaded_curve(low)
    assert capacity==1.
    np.testing.assert_array_equal(soc,[0,.5,1])
    np.testing.assert_array_equal(voltage,[3.,3.7,4.1])


def test_bounded_fit_reoptimizes_coupled_parameter_at_constraint():
    # Unconstrained optimum is (2,1). Constraining the first parameter to 1
    # changes the second optimum to 1.5; simple clipping would be incorrect.
    got=bounded_two(np.array([[2.,1.],[1.,2.]]),np.array([5.,4.]),
                    np.array([0.,0.]),np.array([1.,3.]))
    np.testing.assert_allclose(got,[1.,1.5],atol=1e-15)


def test_real_p7_assessment_voltage_poison_cannot_change_training(monkeypatch):
    monkeypatch.chdir(ROOT)
    try: archive=source_archive()
    except ValueError: pytest.skip('Requires official archive')
    with ZipFile(archive) as z:
        low,_=read_cell(z,'P7','low_rate');frame,_=read_cell(z,'P7','hppc')
    q,a,s,n=prepare(low,frame,PLAN['calibration_cycles'])
    poisoned=frame.copy()
    # Deliberately absurd voltages on BOTH non-calibration allocations.
    poisoned.loc[poisoned.cycle.isin(PLAN['assessment_cycles']+PLAN['development_cycles']),'V_V']+=1000.
    q2,a2,s2,n2=prepare(low,poisoned,PLAN['calibration_cycles'])
    assert q==q2 and a==a2 and n==n2
    for c in PLAN['calibration_cycles']:
        pd.testing.assert_frame_equal(s[c],s2[c])
    # Assessment current/SOC/reference remain legitimate simulation inputs;
    # changing its measured output must never change that reference.
    for c in PLAN['assessment_cycles']:
        np.testing.assert_array_equal(s[c].reference_V,s2[c].reference_V)
    clean=fit_candidates(s,PLAN['calibration_cycles'],PLAN)
    changed=fit_candidates(s2,PLAN['calibration_cycles'],PLAN)
    assert clean==changed


def test_whole_cycles_reserved_and_protected_inputs_unchanged(monkeypatch):
    monkeypatch.chdir(ROOT)
    lock=verify_inputs(check_archive=False)
    groups=[PLAN[k] for k in ['calibration_cycles','development_cycles','assessment_cycles']]
    assert len(sum(groups,[]))==len(set(sum(groups,[])))==9
    for cell in lock['cells'].values():
        cycles=cell['cycles']
        for a,b in zip(range(1,9),range(2,10)):
            assert cycles[str(a)]['source_last_row']+1==cycles[str(b)]['source_first_row']
        for c in PLAN['assessment_cycles']:
            assert {11,12,13,14,15,22}.issubset(cycles[str(c)]['steps'])


def test_provenance_guard_rejects_changed_protected_input(tmp_path,monkeypatch):
    import voltforge.models.identification as ident
    plan=tmp_path/'plan.json';plan.write_text('{}')
    protected=tmp_path/'original.json';protected.write_text('original')
    lock=tmp_path/'lock.json'
    lock.write_text(json.dumps({'plan_sha256':ident.digest(plan),'protected_existing':{str(protected):ident.digest(protected)}}))
    monkeypatch.setattr(ident,'PLAN',plan);monkeypatch.setattr(ident,'LOCK',lock)
    protected.write_text('changed')
    with pytest.raises(ValueError,match='Protected provenance'):
        ident.verify_inputs(check_archive=False)
